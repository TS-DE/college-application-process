"""Agent 提示词（0.13.0）。

## 为什么单独一个文件
提示词是「策略」，调度逻辑是「机制」。放在一起会让 `runner.py` 变成
第二份 `rag_service.py`（什么都往里塞）。独立出来后：
    · 调 Prompt 措辞不用改代码逻辑（只改文案）；
    · 新增一种 Agent 行为（如「多轮澄清」）只需加模板。

## 给 qwen3:4b 的写法要点
小模型对长指令不敏感，因此：
    · 用「必须 / 不要」这类硬约束，不用「建议 / 可以」；
    · 工具选择规则写成「什么场景用什么」，比抽象描述更有效；
    · 显式要求「没有把握就别编数字」，这是本项目防幻觉的底线。
"""
